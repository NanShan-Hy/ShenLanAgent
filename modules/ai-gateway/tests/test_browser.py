import os

import httpx
from playwright.sync_api import expect, sync_playwright

from aigateway.app import create_app
from aigateway.core import Database, Settings, create_user
from conftest import PASSWORD, chat_result
from live import BROWSER_LIBS, serve


def test_browser_resource_wallet_key_and_mobile(tmp_path):
    settings=Settings(tmp_path/'data',tmp_path/'config/master.key',allow_private_upstreams=True,min_free_bytes=0)
    db=Database(settings);db.initialize()
    with db.transaction() as c:create_user(c,'admin','运营管理员',PASSWORD,admin=True)
    app=create_app(settings,upstream_transport=httpx.MockTransport(lambda r:httpx.Response(200,
        json={'data':[{'id':'upstream-model'}]} if r.method=='GET' else chat_result())))
    errors=[]
    with serve(app) as url,sync_playwright() as p:
        settings.public_url=url
        browser=p.chromium.launch(env={**os.environ,'LD_LIBRARY_PATH':BROWSER_LIBS})
        page=browser.new_page(viewport={'width':1440,'height':1000})
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(url)
        page.get_by_label('账号',exact=True).fill('admin')
        page.get_by_label('密码',exact=True).fill(PASSWORD)
        page.get_by_role('button',name='登录控制台',exact=True).click()
        expect(page.get_by_role('heading',name='工作区概览',exact=True)).to_be_visible()
        page.get_by_role('button',name='运营管理',exact=True).click()
        page.get_by_role('button',name='新增资源池',exact=True).click()
        d=page.get_by_role('dialog')
        d.get_by_label('资源池名称',exact=True).fill('独立协议资源池')
        d.get_by_label('共享限流分组',exact=True).fill('browser-qa')
        d.get_by_label('启用资源池',exact=True).check()
        d.get_by_role('button',name='保存',exact=True).click()
        expect(page.get_by_text('独立协议资源池',exact=True)).to_be_visible()
        page.get_by_role('button',name='新增上游',exact=True).click()
        d=page.get_by_role('dialog')
        d.get_by_label('上游名称',exact=True).fill('本地协议上游')
        d.get_by_label('提供商',exact=True).select_option('compatible')
        d.get_by_label('上游Base URL',exact=True).fill('https://provider.test/v1')
        d.get_by_label('上游API密钥',exact=True).fill('synthetic-browser-secret-ONLY-QA')
        d.get_by_label('启用上游',exact=True).check()
        d.get_by_role('button',name='保存',exact=True).click()
        expect(page.get_by_text('本地协议上游',exact=True)).to_be_visible()
        page.get_by_role('button',name='连接测试',exact=True).click()
        expect(page.get_by_role('dialog').get_by_text('upstream-model',exact=True)).to_be_visible()
        page.get_by_role('button',name='创建路由',exact=True).click()
        d=page.get_by_role('dialog')
        expect(d.get_by_label('上游实际模型ID',exact=True)).to_have_value('upstream-model')
        expect(d.get_by_label('启用模型路由',exact=True)).not_to_be_checked()
        expect(d.get_by_label('输入价格（元/百万Token）',exact=True)).to_have_value('')
        d.get_by_label('对外模型名称',exact=True).fill('qa-model')
        d.get_by_label('上游实际模型ID',exact=True).fill('upstream-model')
        d.get_by_label('提供商类型',exact=True).select_option('compatible')
        d.get_by_label('开放协议',exact=True).fill('chat, responses, compact')
        d.get_by_label('输入价格（元/百万Token）',exact=True).fill('1')
        d.get_by_label('缓存输入价格（元/百万Token）',exact=True).fill('0.5')
        d.get_by_label('输出价格（元/百万Token）',exact=True).fill('2')
        d.get_by_label('启用模型路由',exact=True).check()
        d.get_by_role('button',name='保存',exact=True).click()
        expect(page.get_by_text('qa-model',exact=True)).to_be_visible()
        row=page.get_by_role('row').filter(has_text='本地协议上游')
        row.get_by_role('button',name='编辑',exact=True).click()
        expect(page.get_by_label('上游API密钥',exact=True)).to_have_value('')
        page.keyboard.press('Escape')
        page.get_by_role('button',name='连接池状态',exact=True).click()
        expect(page.get_by_role('heading',name='上游调度状态',exact=True)).to_be_visible()
        expect(page.get_by_text('正常调度',exact=True)).to_be_visible()
        page.screenshot(path=str(tmp_path/'gateway-pool-status.png'),full_page=True)
        page.get_by_role('button',name='钱包与套餐',exact=True).click()
        page.get_by_role('button',name='创建充值订单',exact=True).click()
        d=page.get_by_role('dialog')
        d.get_by_label('充值金额（元）',exact=True).fill('1.00')
        d.get_by_role('button',name='创建订单',exact=True).click()
        expect(page.get_by_text('待核款',exact=True)).to_be_visible()
        page.get_by_role('button',name='运营管理',exact=True).click()
        page.get_by_role('button',name='订单与套餐',exact=True).click()
        page.get_by_role('button',name='确认到账',exact=True).click()
        d=page.get_by_role('dialog')
        d.get_by_label('到账核验依据',exact=True).fill('合成QA到账核验，不是真实收款')
        d.get_by_role('button',name='确认入账',exact=True).click()
        expect(page.get_by_text('已入账',exact=True)).to_be_visible()
        page.get_by_role('button',name='应用与密钥',exact=True).click()
        page.get_by_role('button',name='创建平台Key',exact=True).click()
        d=page.get_by_role('dialog')
        d.get_by_label('Key名称',exact=True).fill('浏览器验收Key')
        d.get_by_label('每日Token',exact=True).fill('100000')
        d.get_by_role('button',name='创建Key',exact=True).click()
        secret=page.get_by_role('dialog').get_by_label('平台Key',exact=True).input_value()
        assert secret.startswith('sk-gw-')
        page.get_by_role('dialog').get_by_role('button',name='关闭',exact=True).click()
        with httpx.Client(trust_env=False) as client:
            r=client.post(url+'/v1/chat/completions',headers={'Authorization':'Bearer '+secret},
                          json={'model':'qa-model','messages':[{'role':'user','content':'浏览器验收合成问题'}],'max_tokens':100})
            assert r.status_code==200,r.text
        page.get_by_role('button',name='用量与请求',exact=True).click()
        expect(page.get_by_role('table').get_by_text('已完成',exact=True)).to_be_visible()
        page.get_by_role('button',name='详情',exact=True).click()
        expect(page.get_by_role('dialog').get_by_role('heading',name='请求详情',exact=True)).to_be_visible()
        page.keyboard.press('Escape')
        page.get_by_role('button',name='运营管理',exact=True).click()
        page.get_by_role('button',name='请求审计',exact=True).click()
        page.get_by_role('button',name='尝试记录',exact=True).click()
        expect(page.get_by_role('dialog').get_by_role('heading',name='上游尝试记录',exact=True)).to_be_visible()
        expect(page.get_by_role('dialog').get_by_text('本地协议上游',exact=True)).to_be_visible()
        page.keyboard.press('Escape')
        page.get_by_role('button',name='工作区概览',exact=True).click()
        expect(page.get_by_role('heading',name='工作区概览',exact=True)).to_be_visible()
        page.screenshot(path=str(tmp_path/'gateway-overview.png'),full_page=True)
        page.get_by_role('button',name='接入文档',exact=True).click()
        expect(page.get_by_role('heading',name='Codex CLI / IDE',exact=True)).to_be_visible()
        page.get_by_role('button',name='钱包与套餐',exact=True).click()
        page.set_viewport_size({'width':390,'height':844})
        page.evaluate('scrollTo(0,0)')
        expect(page.locator('.sidebar')).to_have_css('transform','matrix(1, 0, 0, 1, -236, 0)')
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.screenshot(path=str(tmp_path/'gateway-mobile.png'),full_page=True)
        page.get_by_role('button',name='打开菜单',exact=True).click()
        page.get_by_role('button',name='空间与成员',exact=True).click()
        expect(page.get_by_role('heading',name='空间与成员',exact=True)).to_be_visible()
        assert not errors,errors
        browser.close()
