import os

from playwright.sync_api import sync_playwright, expect

from conftest import BROWSER_LIBS, PASSWORD, serve
from testdock.worker import Worker


def test_visual_workflows(targets, tmp_path):
    client, db, settings, api = targets
    errors = []
    with serve(api) as base, sync_playwright() as p:
        browser = p.chromium.launch(env={**os.environ, 'LD_LIBRARY_PATH': BROWSER_LIBS})
        page = browser.new_page(viewport={"width": 1440, "height": 1050})
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(base)
        page.get_by_label('账号', exact=True).fill('admin')
        page.get_by_label('密码', exact=True).fill(PASSWORD)
        page.get_by_role('button', name='登录工作台').click()
        expect(page.get_by_role('heading', name='测试工作台')).to_be_visible()
        page.get_by_role('button', name='环境管理', exact=True).click()
        page.get_by_role('button', name='添加环境', exact=True).click()
        dialog = page.get_by_role('dialog')
        dialog.get_by_label('环境名称').fill('预发 · UI 创建')
        dialog.get_by_label('API 基础地址').fill(db.one('SELECT api_base_url FROM environments WHERE id=1')['api_base_url'])
        dialog.get_by_label('普通变量 · JSON').fill('{"expected":true}')
        dialog.get_by_label('新增 / 更新敏感变量 · JSON').fill('{"api_key":"ui-secret-value"}')
        dialog.get_by_role('button', name='保存', exact=True).click()
        expect(page.get_by_role('heading', name='预发 · UI 创建')).to_be_visible()
        page.get_by_role('button', name='测试用例', exact=False).first.click()
        page.get_by_role('button', name='新建用例', exact=True).first.click()
        dialog = page.get_by_role('dialog')
        dialog.get_by_label('用例名称').fill('UI 创建 · 健康接口')
        dialog.get_by_label('操作', exact=True).select_option('http')
        dialog.get_by_label('URL / 相对路径').fill('/api/info')
        dialog.get_by_role('button', name='添加断言').click()
        dialog.get_by_placeholder('JMESPath，例如 data.id').nth(1).fill('ready')
        dialog.get_by_placeholder('预期值 / {{变量}}').nth(1).fill('true')
        dialog.get_by_role('button', name='保存', exact=True).click()
        expect(page.get_by_text('UI 创建 · 健康接口', exact=True)).to_be_visible()
        page.get_by_role('button', name='测试套件', exact=True).click()
        page.get_by_role('button', name='新建套件', exact=True).click()
        dialog = page.get_by_role('dialog')
        dialog.get_by_label('套件名称').fill('UI 创建 · 冒烟')
        dialog.get_by_label('UI 创建 · 健康接口').check()
        dialog.get_by_role('button', name='保存', exact=True).click()
        row = page.get_by_role('row').filter(has_text='UI 创建 · 冒烟')
        row.get_by_role('button', name='运行套件').click()
        page.get_by_role('dialog').get_by_role('button', name='提交执行').click()
        expect(page.get_by_role('dialog', name='执行报告')).to_be_visible()
        Worker(settings).run_once()
        expect(page.get_by_role('dialog').get_by_text('已通过', exact=True).first).to_be_visible(timeout=10000)
        page.get_by_role('dialog').get_by_role('button', name='关闭', exact=True).first.click()
        page.get_by_role('button', name='定时任务', exact=True).click()
        page.get_by_role('button', name='新建定时任务', exact=True).first.click()
        dialog = page.get_by_role('dialog')
        dialog.get_by_label('任务名称').fill('UI 创建 · 计划')
        dialog.get_by_label('启用任务').uncheck()
        dialog.get_by_role('button', name='保存', exact=True).click()
        expect(page.get_by_text('UI 创建 · 计划', exact=True)).to_be_visible()
        page.get_by_role('button', name='成员与集成', exact=True).click()
        page.get_by_role('button', name='创建账号', exact=True).click()
        dialog = page.get_by_role('dialog')
        dialog.get_by_label('账号', exact=True).fill('ui-tester')
        dialog.get_by_label('姓名').fill('UI 测试员')
        dialog.get_by_label('初始密码').fill('temporary-password')
        dialog.get_by_role('button', name='保存', exact=True).click()
        page.get_by_role('button', name='添加成员', exact=True).click()
        dialog = page.get_by_role('dialog')
        uid = db.one("SELECT id FROM users WHERE username='ui-tester'")['id']
        dialog.get_by_label('用户').select_option(str(uid))
        dialog.get_by_label('角色').select_option('tester')
        dialog.get_by_role('button', name='保存', exact=True).click()
        expect(page.get_by_role('row').filter(has_text='ui-tester').first).to_be_visible()
        page.get_by_role('button', name='创建令牌', exact=True).click()
        page.get_by_role('dialog').get_by_label('令牌名称').fill('UI CI token')
        page.get_by_role('dialog').get_by_role('button', name='创建并显示').click()
        expect(page.get_by_role('dialog', name='请保存此令牌')).to_be_visible()
        assert page.get_by_label('CI Bearer Token').input_value().startswith('td_')
        page.keyboard.press('Escape')
        page.get_by_role('button', name='项目管理', exact=True).click()
        page.get_by_role('button', name='创建项目', exact=True).click()
        page.get_by_role('dialog').get_by_label('项目名称').fill('UI 创建的项目')
        page.get_by_role('dialog').get_by_role('button', name='保存', exact=True).click()
        expect(page.get_by_role('heading', name='UI 创建的项目')).to_be_visible()
        page.get_by_label('当前项目').select_option('1')
        page.get_by_role('button', name='工作台', exact=True).click()
        expect(page.get_by_role('heading', name='测试工作台')).to_be_visible()
        page.screenshot(path=str(tmp_path / 'dashboard.png'), full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.set_viewport_size({"width": 390, "height": 844})
        page.get_by_role('button', name='展开菜单').click()
        page.get_by_role('button', name='测试用例', exact=False).first.click()
        expect(page.get_by_role('heading', name='测试用例')).to_be_visible()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(tmp_path / 'mobile.png'), full_page=True)
        browser.close()
    assert not errors, errors
